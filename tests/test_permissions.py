"""Exercise privileged setup with fake udev commands and a temporary rules directory."""
from contextlib import redirect_stdout
import io
import json
from pathlib import Path
from subprocess import CompletedProcess
from types import SimpleNamespace

import pytest

from dps150ctl import permissions
from dps150ctl.cli import main
from dps150ctl.errors import ControlError

SERIAL = "TEST-USB-1234"
ACCOUNT = SimpleNamespace(pw_name="operator", pw_uid=1234)
DEVICE = {"port": "/dev/ttyACM7", "vid": 0x2e3c, "pid": 0x5740,
          "serial_number": SERIAL, "candidate": True}


@pytest.fixture(autouse=True)
def permission_environment(monkeypatch, tmp_path):
    monkeypatch.setattr("dps150ctl.identity.ports", lambda: [])
    monkeypatch.setattr(permissions.os, "geteuid", lambda: 1234)
    monkeypatch.setattr(permissions.pwd, "getpwuid", lambda uid: ACCOUNT)

    def account(name):
        if name == "operator":
            return ACCOUNT
        if name == "root":
            return SimpleNamespace(pw_name="root", pw_uid=0)
        raise KeyError(name)

    monkeypatch.setattr(permissions.pwd, "getpwnam", account)
    monkeypatch.delenv("SUDO_USER", raising=False)
    monkeypatch.setattr(permissions, "RULES_DIRECTORY", tmp_path / "rules.d")
    setfacl = tmp_path / "setfacl"
    setfacl.write_text("fake executable")
    setfacl.chmod(0o755)
    monkeypatch.setattr(permissions, "SETFACL", setfacl)
    monkeypatch.setattr(permissions.shutil, "which", lambda name: "/usr/bin/udevadm")
    calls = []

    def run(arguments):
        calls.append(arguments)
        output = ""
        if arguments[1] == "--version":
            output = "261\n"
        elif arguments[1] == "info":
            assert arguments[-1] == "--name=/dev/ttyACM7"
            output = "/devices/pci0000:00/usb1/1-7/tty/ttyACM7\n"
        elif arguments[1] == "verify":
            assert Path(arguments[2]).read_text().startswith("# Generated by dps150ctl:")
        return CompletedProcess(arguments, 0, stdout=output, stderr="")

    monkeypatch.setattr(permissions, "_run", run)
    return calls


def rule():
    return permissions.prepare_rule(serial_number=SERIAL)


def test_preview_uses_bundled_template_without_installing():
    result = rule()
    assert f'ATTRS{{serial}}=="{SERIAL}"' in result.text
    assert 'ATTRS{idVendor}=="2e3c"' in result.text
    assert 'ATTRS{idProduct}=="5740"' in result.text
    assert "u:1234:rw $env{DEVNAME}" in result.text
    assert "@SERIAL@" not in result.text and "@UID@" not in result.text
    assert "operator" not in result.text
    assert not permissions.RULES_DIRECTORY.exists()


@pytest.mark.parametrize("serial", ["*", "?", "S[12]", "../supply", 'bad"serial',
                                    "bad\nserial", "bad\\serial", "bad$serial", "bad%serial", "x" * 129])
def test_serial_must_be_literal_not_a_pattern_or_injection(serial):
    with pytest.raises(ControlError, match="literal USB serial"):
        permissions.prepare_rule(serial_number=serial)
    assert not permissions.RULES_DIRECTORY.exists()


def test_auto_discovery_and_explicit_selection(monkeypatch):
    monkeypatch.setattr("dps150ctl.identity.ports", lambda: [DEVICE])
    assert permissions.prepare_rule().identity.serial_number == SERIAL
    other = {**DEVICE, "serial_number": "SECOND", "port": "/dev/ttyACM8"}
    monkeypatch.setattr("dps150ctl.identity.ports", lambda: [DEVICE, other])
    with pytest.raises(ControlError) as error:
        permissions.prepare_rule()
    assert error.value.code == "ambiguous"
    assert permissions.prepare_rule(serial_number="SECOND").identity.port == "/dev/ttyACM8"


def test_no_serial_or_unrelated_usb_id_is_rejected(monkeypatch):
    with pytest.raises(ControlError, match="literal USB serial"):
        permissions.prepare_rule(port="/test/serial")
    monkeypatch.setattr("dps150ctl.identity.ports", lambda: [{**DEVICE, "vid": 0x1234}])
    with pytest.raises(ControlError, match="requires a 2e3c:5740"):
        permissions.prepare_rule(port=DEVICE["port"])


def test_sudo_selects_invoking_user_and_root_requires_explicit_user(monkeypatch):
    monkeypatch.setattr(permissions.os, "geteuid", lambda: 0)
    monkeypatch.setenv("SUDO_USER", "operator")
    assert rule().uid == 1234
    monkeypatch.delenv("SUDO_USER")
    with pytest.raises(ControlError, match="specify --user"):
        rule()
    assert permissions.prepare_rule(serial_number=SERIAL, username="operator").uid == 1234


@pytest.mark.parametrize("username", ["missing", "root"])
def test_target_user_must_exist_and_be_nonroot(username):
    with pytest.raises(ControlError):
        permissions.prepare_rule(serial_number=SERIAL, username=username)


def test_install_requires_root_without_side_effects(permission_environment):
    with pytest.raises(ControlError, match="administrator privileges; run: sudo"):
        permissions.install_rule(rule())
    assert not permission_environment
    assert not permissions.RULES_DIRECTORY.exists()


def test_install_applies_only_selected_device_and_is_idempotent(monkeypatch, permission_environment):
    prepared = rule()
    monkeypatch.setattr(permissions.os, "geteuid", lambda: 0)
    monkeypatch.setattr("dps150ctl.identity.ports", lambda: [DEVICE])
    result = permissions.install_rule(prepared)
    installed = Path(result["rule_file"])
    assert installed.read_text() == prepared.text
    assert installed.stat().st_mode & 0o777 == 0o644
    assert result["applied_to"] == "/dev/ttyACM7"
    assert result["uid"] == 1234
    assert permission_environment[-1] == ["/usr/bin/udevadm", "trigger", "--action=change", "--settle",
                                          "/sys/devices/pci0000:00/usb1/1-7/tty/ttyACM7"]
    inode = installed.stat().st_ino
    permissions.install_rule(prepared)
    assert installed.stat().st_ino == inode
    assert list(permissions.RULES_DIRECTORY.iterdir()) == [installed]


def test_offline_install_waits_for_next_add_event(monkeypatch, permission_environment):
    prepared = rule()
    monkeypatch.setattr(permissions.os, "geteuid", lambda: 0)
    result = permissions.install_rule(prepared)
    assert result["applied_to"] is None
    assert not any(call[1] == "trigger" for call in permission_environment)
    assert ["/usr/bin/udevadm", "control", "--reload-rules"] in permission_environment


@pytest.mark.parametrize("symlink", [False, True])
def test_conflicting_files_and_symlinks_are_never_replaced(monkeypatch, tmp_path, symlink):
    prepared = rule()
    monkeypatch.setattr(permissions.os, "geteuid", lambda: 0)
    permissions.RULES_DIRECTORY.mkdir()
    destination = permissions.RULES_DIRECTORY / prepared.filename
    if symlink:
        target = tmp_path / "unrelated"
        target.write_text("keep this")
        destination.symlink_to(target)
    else:
        destination.write_text("keep this")
    with pytest.raises(ControlError) as error:
        permissions.install_rule(prepared)
    assert error.value.code == "conflict"
    assert destination.read_text() == "keep this"
    assert destination.is_symlink() == symlink


def test_missing_acl_dependency_leaves_no_rule(monkeypatch):
    prepared = rule()
    monkeypatch.setattr(permissions.os, "geteuid", lambda: 0)
    permissions.SETFACL.unlink()
    with pytest.raises(ControlError, match="acl package"):
        permissions.install_rule(prepared)
    assert not permissions.RULES_DIRECTORY.exists()


def test_verification_failure_leaves_no_rule(monkeypatch):
    prepared = rule()
    monkeypatch.setattr(permissions.os, "geteuid", lambda: 0)
    normal_run = permissions._run

    def run(arguments):
        if arguments[1] == "verify":
            raise ControlError("udev", "invalid rule")
        return normal_run(arguments)

    monkeypatch.setattr(permissions, "_run", run)
    with pytest.raises(ControlError, match="invalid rule"):
        permissions.install_rule(prepared)
    assert not permissions.RULES_DIRECTORY.exists()


def test_older_udev_can_install_without_verify(monkeypatch, permission_environment):
    prepared = rule()
    monkeypatch.setattr(permissions.os, "geteuid", lambda: 0)
    normal_run = permissions._run

    def run(arguments):
        if arguments[1] == "--version":
            return CompletedProcess(arguments, 0, stdout="252\n", stderr="")
        return normal_run(arguments)

    monkeypatch.setattr(permissions, "_run", run)
    permissions.install_rule(prepared)
    assert not any(call[1] == "verify" for call in permission_environment)


def test_activation_failure_reports_installed_rule(monkeypatch):
    prepared = rule()
    monkeypatch.setattr(permissions.os, "geteuid", lambda: 0)
    normal_run = permissions._run

    def run(arguments):
        if arguments[1] == "control":
            raise ControlError("udev", "reload failed")
        return normal_run(arguments)

    monkeypatch.setattr(permissions, "_run", run)
    with pytest.raises(ControlError, match="rule installed.*activation failed"):
        permissions.install_rule(prepared)
    assert (permissions.RULES_DIRECTORY / prepared.filename).read_text() == prepared.text


def test_cli_preview_bypasses_user_config_and_service_discovery(monkeypatch):
    def forbidden(*args, **kwargs):
        raise AssertionError("permissions setup must not load control configuration or discover services")

    monkeypatch.setattr("dps150ctl.cli.known_services", forbidden)
    monkeypatch.setattr("dps150ctl.cli.Settings.load", forbidden)
    output = io.StringIO()
    with redirect_stdout(output):
        assert main(["--device", SERIAL, "permissions", "show", "--json"]) == 0
    result = json.loads(output.getvalue())
    assert result["usb_serial"] == SERIAL and result["uid"] == 1234
    assert not permissions.RULES_DIRECTORY.exists()


def test_cli_install_error_gives_exact_sudo_command():
    output = io.StringIO()
    with redirect_stdout(output):
        assert main(["--device", SERIAL, "permissions", "install", "--json"]) == 1
    error = json.loads(output.getvalue())["error"]
    assert error["code"] == "permission"
    assert "sudo " in error["message"]
    assert "permissions install --user operator" in error["message"]
    assert not permissions.RULES_DIRECTORY.exists()
